export function shuffled(question) {
  const order = question.options.map((_, i) => i)
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[order[i], order[j]] = [order[j], order[i]]
  }
  return { ...question, options: order.map((i) => question.options[i]), correct: order.indexOf(0) }
}

export function grade(score) {
  if (score >= 13) return 'A’lo natija. Bayroğimiz tarixi va ramzlarini puxta bilasiz.'
  if (score >= 9) return 'Yaxşi natija. Bir neçta tafsilotni «Tarix» bölimida aniqlaştirib olişingiz mumkin.'
  return 'Iştirokingiz uçun rahmat. «Tarix» bölimini öqib, viktorinani qayta topşirib köring.'
}
